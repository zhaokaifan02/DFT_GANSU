// ---- 可用点数列表 ----
const std::vector<int> &chemgrid::lebedev_supported_sizes()
{
    static std::vector<int> sizes = []
    {
        std::vector<int> s;
        s.reserve(::table().size());
        for (auto &kv : ::table())
            s.push_back(kv.first);
        std::sort(s.begin(), s.end());
        return s;
    }();
    return sizes;
}

// ---- 按点数生成 SoA 网格 ----
chemgrid::AngGrid chemgrid::make_lebedev_grid(int n_points)
{
    auto it = ::table().find(n_points);

    std::vector<P4> acc;
    // 粗略预估容量（每条轨道的最大展开 48）
    acc.reserve(static_cast<std::size_t>(n_points));

    for (const Orbit &ob : it->second)
    {
        ::expand_orbit(acc, ob.code, ob.a, ob.b, ob.v);
    }
    // 保险：展开点数应该和 n_points 一致
    assert(acc.size() == static_cast<std::size_t>(n_points));
    return ::to_soa(acc);
}
