    // ---------- 点结构（内部用） ----------
    struct P4
    {
        double x, y, z, w;
    };

    // ---------- 轨道编码 ----------
    enum class OrbitCode : uint8_t
    {
        O6 = 0,       // (±1,0,0) permutations
        O12 = 1,      // (0,±1/√2,±1/√2) permutations
        O8 = 2,       // (±1/√3,±1/√3,±1/√3)
        O24_AA_B = 3, // (±a,±a,±b) permutations, b=√(1-2a²)
        O24_A_B0 = 4, // (±a,±b,0) permutations,  b=√(1-a²)
        O48_A_B_C = 5 // (±a,±b,±c) permutations, c=√(1-a²-b²)
    };

    // ---------- 表项：一条轨道的参数 ----------
    struct Orbit
    {
        OrbitCode code;
        double a, b, v;
    };

    // 展开一个轨道到点集（完全复刻你 Python 的规则）
    static void expand_orbit(std::vector<P4> &out, OrbitCode code, double a, double b, double v)
    {
        auto add = [&](double X, double Y, double Z)
        { out.push_back({X, Y, Z, v}); };

        switch (code)
        {
        case OrbitCode::O6:
        {
            const double s = 1.0;
            add(s, 0, 0);
            add(-s, 0, 0);
            add(0, s, 0);
            add(0, -s, 0);
            add(0, 0, s);
            add(0, 0, -s);
        }
        break;
        case OrbitCode::O12:
        {
            const double t = std::sqrt(0.5);
            // permutations of (0, ±t, ±t)
            add(0.0, t, t);
            add(0.0, -t, t);
            add(0.0, t, -t);
            add(0.0, -t, -t);
            // permutations of (±t, 0, ±t)
            add(t, 0.0, t);
            add(-t, 0.0, t);
            add(t, 0.0, -t);
            add(-t, 0.0, -t);
            // permutations of (±t, ±t, 0)
            add(t, t, 0.0);
            add(-t, t, 0.0);
            add(t, -t, 0.0);
            add(-t, -t, 0.0);
        }
        break;
        case OrbitCode::O8:
        {
            const double t = std::sqrt(1.0 / 3.0);
            add(t, t, t);
            add(-t, t, t);
            add(t, -t, t);
            add(-t, -t, t);
            add(t, t, -t);
            add(-t, t, -t);
            add(t, -t, -t);
            add(-t, -t, -t);
        }
        break;
        case OrbitCode::O24_AA_B:
        {
            // (±a, ±a, ±b) with all permutations
            double aa = a;
            double bb = std::sqrt(std::max(0.0, 1.0 - 2.0 * a * a));
            add(a,a,bb);
            add(-a,a,bb);
            add(a,-a,bb);
            add(-a,-a,bb);

            add(a,a,-bb);
            add(-a,a,-bb);
            add(a,-a,-bb);
            add(-a,-a,-bb);

            add(a,bb,a);
            add(-a,bb,a);
            add(a,-bb,a);
            add(-a,-bb,a);

            add(a,bb,-a);
            add(-a,bb,-a);
            add(a,-bb,-a);
            add(-a,-bb,-a);

            add(bb,a,a);
            add(-bb,a,a);
            add(bb,-a,a);
            add(-bb,-a,a);

            add(bb,a,-a);
            add(-bb,a,-a);
            add(bb,-a,-a);
            add(-bb,-a,-a);
        }
        break;
        case OrbitCode::O24_A_B0:
        {
            double aa = a;
            double bb = std::sqrt(std::max(0.0, 1.0 - a * a));
            add(aa,bb,0.0);
            add(-aa,bb,0.0);
            add(aa,-bb,0.0);
            add(-aa,-bb,0.0);

            add(bb,aa,0.0);
            add(-bb,aa,0.0);
            add(bb,-aa,0.0);
            add(-bb,-aa,0.0);
            
            add(aa,0.0,bb);
            add(-aa,0.0,bb);
            add(aa,0.0,-bb);
            add(-aa,0.0,-bb);

            add(bb,0.0,aa);
            add(-bb,0.0,aa);
            add(bb,0.0,-aa);
            add(-bb,0.0,-aa);

            add(0.0,aa,bb);
            add(0.0,-aa,bb);
            add(0.0,aa,-bb);
            add(0.0,-aa,-bb);

            add(0.0,bb,aa);
            add(0.0,-bb,aa);
            add(0.0,bb,-aa);
            add(0.0,-bb,-aa);
        }
        break;
        case OrbitCode::O48_A_B_C:
        {
            double aa = a, bb = b;
            double cc = std::sqrt(std::max(0.0, 1.0 - a * a - b * b));
            const double A[2] = {aa, -aa};
            const double B[2] = {bb, -bb};
            const double C[2] = {cc, -cc};
            // all permutations of (a,b,c) with signs
            for (double sx : A)
                for (double sy : B)
                    for (double sz : C)
                    {
                        add(sx, sy, sz);
                        add(sx, sz, sy);
                        add(sy, sx, sz);
                        add(sy, sz, sx);
                        add(sz, sx, sy);
                        add(sz, sy, sx);
                    }
        }
        break;
        }
    }

    // ---------- 小工具：把 P4[] 搬进 SoA ----------
    static cg::AngGrid to_soa(const std::vector<P4> &pts)
    {
        cg::AngGrid g;
        g.reserve(pts.size());
        for (const auto &p : pts)
            g.push(p.x, p.y, p.z, p.w);
        return g;
    }

